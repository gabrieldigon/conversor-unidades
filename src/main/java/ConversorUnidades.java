public class ConversorUnidades {

    // Método 1: Quilômetros para Milhas (1 km = 0.621371 milhas)
    public double quilometrosParaMilhas(double km) {
        return km * 0.621371;
    }

    // Método 2: Centímetros para Polegadas (1 cm = 0.393701 polegadas)
    public double centimetrosParaPolegadas(double cm) {
        return cm * 0.393701;
    }
}
